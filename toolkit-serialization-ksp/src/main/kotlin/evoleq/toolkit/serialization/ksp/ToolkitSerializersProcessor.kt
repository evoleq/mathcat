package evoleq.toolkit.serialization.ksp

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.ClassKind
import com.google.devtools.ksp.symbol.KSAnnotated
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.Modifier
import com.google.devtools.ksp.validate

/** KSP2 build-time adapter. Neither this module nor its classes are runtime dependencies. */
class ToolkitSerializersProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        ToolkitSerializersProcessor(
            environment.codeGenerator,
            environment.logger,
            environment.options["toolkit.serializers.package"]
                ?: "evoleq.toolkit.serialization.generated",
            environment.options["toolkit.serializers.name"]
                ?: "GeneratedSerializers"
        )
}

private class ToolkitSerializersProcessor(
    private val generator: CodeGenerator,
    private val logger: KSPLogger,
    private val outputPackage: String,
    private val outputName: String
) : SymbolProcessor {
    private var written = false
    private val packageFormat = Regex("[A-Za-z_][A-Za-z_0-9]*(\\.[A-Za-z_][A-Za-z_0-9]*)*")
    private val identifierFormat = Regex("[A-Za-z_][A-Za-z_0-9]*")

    override fun process(resolver: Resolver): List<KSAnnotated> {
        if (written) return emptyList()
        if (!packageFormat.matches(outputPackage) || !identifierFormat.matches(outputName)) {
            logger.error("Invalid Toolkit generated package or registry name")
            written = true
            return emptyList()
        }

        // Only this compilation's sources; do not silently scan transitive dependencies.
        val annotated = resolver.getSymbolsWithAnnotation("kotlinx.serialization.Serializable")
            .filterIsInstance<KSClassDeclaration>()
            .filter { it.containingFile != null }
            .toList()

        val deferred = annotated.filterNot { it.validate() }
        if (deferred.isNotEmpty()) return deferred

        val eligible = annotated.filter { declaration ->
            val excluded = declaration.annotations.any {
                it.annotationType.resolve().declaration.qualifiedName?.asString() ==
                    "evoleq.toolkit.serialization.SkipAutoSerializer"
            }
            val visible = Modifier.PRIVATE !in declaration.modifiers &&
                Modifier.PROTECTED !in declaration.modifiers
            val supportedKind = declaration.classKind in setOf(
                ClassKind.CLASS,
                ClassKind.OBJECT,
                ClassKind.ENUM_CLASS
            ) || (declaration.classKind == ClassKind.INTERFACE &&
                Modifier.SEALED in declaration.modifiers)
            val notGeneric = declaration.typeParameters.isEmpty()
            if (!notGeneric && !excluded) {
                logger.warn(
                    "Skipping generic Serializable " +
                        declaration.qualifiedName?.asString() +
                        "; register a specialized serializer manually",
                    declaration
                )
            }
            !excluded && visible && supportedKind && notGeneric &&
                declaration.qualifiedName != null
        }.sortedBy { it.qualifiedName?.asString() }

        // Aggregating output tracks *all* input files; each consumer owns its registry.
        val files = annotated.mapNotNull { it.containingFile }.distinct().toTypedArray()
        val out = generator.createNewFile(
            Dependencies(true, *files),
            outputPackage,
            outputName,
            "kt"
        )
        out.bufferedWriter().use { writer ->
            writer.appendLine("package " + outputPackage)
            writer.appendLine()
            writer.appendLine("// Generated by Toolkit KSP. Do not edit.")
            writer.appendLine("public val " + outputName +
                ": evoleq.toolkit.serialization.Serializers =")
            writer.appendLine("    evoleq.toolkit.serialization.Serializers {")
            for (declaration in eligible) {
                val name = declaration.qualifiedName!!.asString()
                writer.appendLine("        add(" + name + "::class, " + name + ".serializer())")
            }
            writer.appendLine("    }")
        }
        written = true
        return emptyList()
    }
}
